// Handoff file: a short, regenerated summary of one work item so a new session can resume without re-reading artifacts.
import fs from 'node:fs';
import path from 'node:path';
import { handoffRel, now, repoDir, specDirAbs, childrenOf } from './state.mjs';
import { currentBranch, headSha } from './git.mjs';
import { checkTasks, requiredGates } from './gates.mjs';
import { latestEvidence, readEvidence } from './verify.mjs';
import { nextAction } from './render.mjs';

const MAX_LINES = 60;
const short = (s) => (s ? String(s).slice(0, 8) : '-');
const oneLine = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();

export function renderHandoff(ctx, f) {
  const parent = f.parent ? ctx.backlog.features.find((x) => x.id === f.parent) : null;
  const open = f.rework.find((r) => !r.closed_at);
  const rw = open ? `, rework round ${open.n}` : f.rework.length ? `, ${f.rework.length} rework round(s) closed` : '';
  const kind = parent ? ` (slice of ${parent.id})` : f.kind !== 'feature' ? ` (${f.kind})` : '';
  const L = [
    '<!-- generated by specflow checkpoint; do not edit, run `specflow checkpoint <id> --note/--next` -->',
    `# Handoff: ${f.id} ${oneLine(f.title)}${kind} — stage ${f.stage}${rw}`,
    `Updated: ${now()}   Lane: ${f.lane}   Milestone: ${f.milestone || '-'}`,
    '## Next step',
    oneLine(f.checkpoint?.next) || nextAction(ctx, f),
    '## Note',
    oneLine(f.checkpoint?.note) || '-',
    '## Progress',
  ];
  const tasks = f.spec_dir ? checkTasks(ctx, f) : null;
  const req = requiredGates(ctx, f);
  const approved = req.filter((g) => f.gates[g]);
  const kids = childrenOf(ctx, f.id);
  L.push([
    tasks && tasks.total ? `tasks ${tasks.done}/${tasks.total}` : kids.length ? `slices ${kids.filter((k) => k.stage === 'done').length}/${kids.length} done` : 'no tasks yet',
    `gates approved: ${approved.join(', ') || '-'}`,
    `pending: ${req.filter((g) => !f.gates[g]).join(', ') || '-'}`,
  ].join('; '));
  L.push('## Repos');
  if (f.repos.length) {
    const ev = readEvidence(ctx, f);
    L.push('| repo | branch | HEAD | last verified | fresh |', '|---|---|---|---|---|');
    for (const name of f.repos) {
      const repo = ctx.config.repos.find((r) => r.name === name);
      const dir = repo && repoDir(ctx, repo);
      const head = dir ? headSha(dir) : null;
      const last = latestEvidence(ev, name, ['test', 'manual']);
      L.push(`| ${name} | ${f.branches[name] || (dir && currentBranch(dir)) || '-'} | ${short(head)} | ${last ? short(last.sha) : '-'} | ${last && head && last.sha === head ? 'yes' : 'no'} |`);
    }
  } else L.push('(no repos)');
  const lastN = (arr, fmt) => (arr.length ? arr.slice(-5).map(fmt) : ['-']);
  L.push('## Open blockers', ...lastN(f.blockers.filter((b) => b.open), (b) => `- ${b.id} [${b.kind}] ${oneLine(b.text)}`));
  L.push('## Open questions', ...lastN(ctx.backlog.questions.filter((q) => q.status === 'open' && q.feature === f.id), (q) => `- ${q.id} (to ${q.to}) ${oneLine(q.text)}`));
  L.push('## Recent decisions', ...lastN(ctx.memory.decisions.filter((d) => d.scope === f.id || d.scope === 'project'), (d) => `- ${d.id} ${oneLine(d.question)} -> ${oneLine(d.answer)}`));
  const delivered = Object.entries(f.delivery || {});
  if (delivered.length) L.push('## Delivery', ...delivered.map(([r, d]) => `- ${r}: ${d.pr_url} (${d.pr_state})`));
  L.push('## Artifacts');
  const dir = specDirAbs(ctx, f);
  const links = dir ? ['spec.md', 'plan.md', 'tasks.md', 'verification.md', 'ux.md'].filter((n) => fs.existsSync(path.join(dir, n))).map((n) => `- ${f.spec_dir}/${n}`) : [];
  L.push(...(links.length ? links : ['-']));
  return L.slice(0, MAX_LINES).join('\n') + '\n';
}

/** (Re)writes the handoff file for `f`; returns its path relative to the root. Never touches state. */
export function writeHandoff(ctx, f) {
  const rel = handoffRel(ctx, f);
  const abs = path.resolve(ctx.root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, renderHandoff(ctx, f));
  return rel;
}

/** Best-effort variant for automatic regeneration: a handoff problem must never fail a state change. */
export function refreshHandoff(ctx, f) {
  try { return writeHandoff(ctx, f); } catch { return null; }
}
