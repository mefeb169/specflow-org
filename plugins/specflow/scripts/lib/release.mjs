// Release pipeline: a generated plan for the owner or the release role, and step-by-step runs with evidence.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { UserError, getRepo, inDeployOrder, logHistory, now, repoDir, stateDirName } from './state.mjs';
import { headSha } from './git.mjs';
import { openBlockers, traits } from './gates.mjs';
import { deliveryCfg, releaseCfg, stepApproval } from './team.mjs';
import { appendEvidence, tail } from './verify.mjs';

const ROLLBACK_PLACEHOLDER = '(to be filled by the release role or the owner: how to undo each step, and the last known good version)';

export const releaseFile = (ctx, f) => (f.spec_dir ? `${f.spec_dir}/release.md` : `${stateDirName(ctx.root)}/release/${f.id}.md`);

/** The body of the "## Rollback" section of an existing release.md (kept across regenerations). */
function keptRollback(abs) {
  if (!fs.existsSync(abs)) return ROLLBACK_PLACEHOLDER;
  const text = fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
  const at = text.indexOf('\n## Rollback\n');
  if (at < 0) return ROLLBACK_PLACEHOLDER;
  const rest = text.slice(at + '\n## Rollback\n'.length);
  const end = rest.search(/^(## |Generated by specflow release plan)/m);
  const body = (end < 0 ? rest : rest.slice(0, end)).trim();
  return body || ROLLBACK_PLACEHOLDER;
}

export function releasePlan(ctx, f) {
  const cfg = releaseCfg(ctx);
  const rel = releaseFile(ctx, f);
  const abs = path.resolve(ctx.root, rel);
  const t = traits(ctx, f);
  const steps = cfg.steps.map((s) => ({ name: s.name, repo: s.repo || null, kind: s.kind || 'deploy', approval: stepApproval(s), run: s.run, timeout_s: s.timeout_s }));
  const L = [
    `# Release plan: ${f.id} ${f.title}`,
    '',
    `Kind: ${f.kind} | Release by AI: ${cfg.by_ai ? 'yes' : 'no (the owner follows this plan)'} | Require merged PRs: ${cfg.require_merged ? 'yes' : 'no'}`,
    '',
    '## Repos and pull requests',
    ...(f.repos.length ? inDeployOrder(ctx, f.repos).map((r) => { const d = f.delivery[r]; return `- ${r}: ${d ? `${d.pr_url} (${d.pr_state})` : 'no PR recorded'}`; }) : ['- (no repos)']),
    '',
    '## Migrations',
    t.migration ? '- The plan or tasks mention migrations: run them before the code that needs them, and check them against the plan.' : '- None found in the plan or tasks.',
    '',
    '## Steps (in order)',
    ...(steps.length ? steps.map((s, i) => `${i + 1}. ${s.name} [${s.kind}, approval: ${s.approval}${s.repo ? `, repo: ${s.repo}` : ''}] \`${s.run}\``) : ['(no steps configured: `specflow release step add`)']),
    '',
    '## Post-release checks',
    ...(cfg.post_release.length ? cfg.post_release.map((s, i) => `${i + 1}. ${s.name}${s.repo ? ` [repo: ${s.repo}]` : ''} \`${s.run}\``) : ['(none configured)']),
    '',
    '## Rollback',
    keptRollback(abs),
    '',
    'Generated by specflow release plan',
  ];
  const text = L.join('\n') + '\n';
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, text);
  return { id: f.id, file: rel, steps, post_release: cfg.post_release, text };
}

function execStep(ctx, f, s, kind) {
  const dir = s.repo ? repoDir(ctx, getRepo(ctx, s.repo)) : ctx.root;
  const r = spawnSync(s.run, { cwd: dir, shell: true, encoding: 'utf8', timeout: (s.timeout_s || (kind === 'release' ? 900 : 120)) * 1000, maxBuffer: 64 * 1024 * 1024 });
  const code = r.status === null ? (r.error ? 'error' : 'signal') : r.status;
  const output = `${r.stdout || ''}${r.stderr || ''}${r.error ? `\n${r.error.message}` : ''}`;
  const result = code === 0 ? 'pass' : 'fail';
  appendEvidence(ctx, f, { kind, repo: s.repo || 'all', command: s.run, exit_code: code, sha: s.repo ? headSha(dir) || 'none' : '', result, note: s.name, tail: tail(output) });
  return { name: s.name, result, exit_code: code, tail: tail(output, 8) };
}

function releasePreconditions(ctx, f) {
  const cfg = releaseCfg(ctx);
  const p = [];
  if (!cfg.by_ai) p.push('release by AI is off (specflow release set --by-ai true); follow `specflow release plan` yourself');
  if (f.stage !== 'accepted') p.push(`stage is ${f.stage}; releasing runs from accepted`);
  if (!f.gates.acceptance) p.push(`acceptance gate is not approved (specflow gate approve ${f.id} acceptance)`);
  if (openBlockers(f).length) p.push(`${openBlockers(f).length} open blocker(s)`);
  if (cfg.require_merged && deliveryCfg(ctx).mode !== 'commit') {
    for (const r of f.repos) {
      const d = f.delivery[r];
      if (!d) p.push(`${r}: no delivered PR (specflow deliver ${f.id})`);
      else if (d.pr_state !== 'MERGED') p.push(`${r}: PR is ${d.pr_state}, not MERGED (merge it, then specflow deliver status ${f.id})`);
    }
  }
  if (!cfg.steps.length) p.push('no release steps configured (specflow release step add)');
  return p;
}

export function releaseRun(ctx, f, { step, again = false } = {}) {
  const problems = releasePreconditions(ctx, f);
  if (problems.length) throw new UserError(`Cannot release ${f.id}:\n${problems.map((x) => `  - ${x}`).join('\n')}`);
  const cfg = releaseCfg(ctx);
  const passed = (s) => f.release_progress[s.name]?.result === 'pass';
  const lines = [];
  const results = [];
  let ok = true;
  let stoppedAt = null;
  let todo = cfg.steps;
  if (step !== undefined) {
    const s = cfg.steps.find((x) => x.name === step);
    if (!s) throw new UserError(`unknown release step "${step}". Steps: ${cfg.steps.map((x) => x.name).join(', ')}`);
    if (passed(s) && !again) throw new UserError(`step "${step}" already passed; use --again to run it again`);
    todo = [s];
  }
  for (const s of todo) {
    if (step === undefined && passed(s) && !again) { lines.push(`${s.name}: already passed, skipped`); continue; }
    if (step === undefined && stepApproval(s) === 'ask') {
      stoppedAt = s.name;
      lines.push(`${s.name} needs approval: tell the user, then run \`specflow release run ${f.id} --step ${s.name}\``);
      break;
    }
    const r = execStep(ctx, f, s, 'release');
    results.push(r);
    f.release_progress[s.name] = { result: r.result, at: now() };
    logHistory(f, 'link', `release step ${s.name}: ${r.result}`);
    lines.push(`${s.name}: ${r.result.toUpperCase()} (exit ${r.exit_code})${r.result === 'fail' ? `\n${r.tail}` : ''}`);
    if (r.result !== 'pass') { ok = false; break; }
  }
  const all = ok && cfg.steps.every(passed);
  if (all) lines.push(`all release steps passed: run \`specflow stage set ${f.id} released\``);
  return { id: f.id, ok, stopped_at: stoppedAt, all_passed: all, results, lines };
}

export function releaseVerify(ctx, f) {
  const cfg = releaseCfg(ctx);
  if (f.stage !== 'released') throw new UserError(`release verify runs at stage released; ${f.id} is at ${f.stage}`);
  if (!cfg.post_release.length) throw new UserError('no post-release checks configured (specflow release step add <name> --run "<cmd>" --post)');
  const results = cfg.post_release.map((s) => execStep(ctx, f, s, 'post-release'));
  for (const r of results) logHistory(f, 'link', `post-release check ${r.name}: ${r.result}`);
  const ok = results.every((r) => r.result === 'pass');
  const lines = results.map((r) => `${r.name}: ${r.result.toUpperCase()} (exit ${r.exit_code})${r.result === 'fail' ? `\n${r.tail}` : ''}`);
  if (ok) lines.push(`post-release checks passed: run \`specflow stage set ${f.id} done\``);
  return { id: f.id, ok, results, lines };
}
