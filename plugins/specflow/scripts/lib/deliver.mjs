// Delivery: push the feature branch and open (or update) ONE pull request per repo, only from a verified state.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { UserError, handoffRel, inDeployOrder, isContainer, logHistory, now, repoDir } from './state.mjs';
import { git, currentBranch, defaultBranch, headSha, isDirty, isGitRepo, remoteUrl } from './git.mjs';
import { stageIdx } from './lifecycle.mjs';
import { openBlockers } from './gates.mjs';
import { deliveryCfg } from './team.mjs';
import { appendEvidence, latestEvidence, readEvidence, tail } from './verify.mjs';

/** SPECFLOW_GH ("path" or `node "script.mjs"`, quotes allowed) replaces `gh`; tests use a fake script. */
function ghArgv() {
  const raw = process.env.SPECFLOW_GH || 'gh';
  const out = [];
  for (const m of raw.matchAll(/"([^"]*)"|'([^']*)'|(\S+)/g)) out.push(m[1] ?? m[2] ?? m[3]);
  return out;
}

export function gh(dir, args) {
  const [cmd, ...pre] = ghArgv();
  const r = spawnSync(cmd, [...pre, ...args], { cwd: dir, encoding: 'utf8' });
  if (r.error) return { ok: false, out: '', err: `cannot run ${cmd}: ${r.error.message}`, missing: true };
  return { ok: r.status === 0, out: (r.stdout || '').trim(), err: (r.stderr || '').trim() };
}

/** Existing PR for a branch: { pr } (null when none) or { error }. */
export function prView(dir, branch) {
  const r = gh(dir, ['pr', 'view', branch, '--json', 'url,state,number']);
  if (r.ok) {
    try { const j = JSON.parse(r.out); return { pr: { url: j.url, state: String(j.state).toUpperCase(), number: j.number } }; } catch { return { error: `unreadable gh output: ${r.out.slice(0, 120)}` }; }
  }
  if (r.missing) return { error: r.err };
  return /no pull requests? found|could not find/i.test(r.err) ? { pr: null } : { error: tail(r.err || r.out, 3) };
}

const mdPath = (f, name) => (f.spec_dir ? `${f.spec_dir}/${name}` : '-');

/** Conditions that apply to the whole item (empty list = ok). */
export function itemProblems(ctx, f) {
  const p = [];
  if (isContainer(ctx, f)) p.push(`${f.id} is split into slices: deliver one of its slices`);
  if (stageIdx(f.stage) < stageIdx('accepted')) p.push(`stage is ${f.stage}; delivery needs accepted or later`);
  const round = f.rework.find((r) => !r.closed_at);
  if (round) p.push(`rework round ${round.n} is open: finish it and verify again before delivering`);
  if (openBlockers(f).length) p.push(`${openBlockers(f).length} open blocker(s)`);
  if (!f.repos.length) p.push('the item has no repos');
  return p;
}

/** Conditions for one repo (empty list = ok). */
export function repoProblems(ctx, f, name, ev) {
  const repo = ctx.config.repos.find((r) => r.name === name);
  if (!repo) return ['repo is not registered'];
  const dir = repoDir(ctx, repo);
  if (!isGitRepo(dir)) return ['not a git repository'];
  const p = [];
  const head = headSha(dir);
  const last = latestEvidence(ev, name, ['test', 'manual']);
  if (!last) p.push(`no test/manual evidence (specflow verify run ${f.id} --repo ${name})`);
  else if (last.result !== 'pass') p.push(`latest verification FAILED (${last.at})`);
  else if ((last.sha || 'none') !== head) p.push(`verification is stale: evidence at ${String(last.sha).slice(0, 8)}, HEAD is ${String(head).slice(0, 8)}`);
  const want = f.branches[name];
  if (!want) p.push('no branch recorded for this item');
  else if (currentBranch(dir) !== want) p.push(`on branch ${currentBranch(dir)}, the item's branch is ${want}`);
  if (isDirty(dir)) p.push('uncommitted changes');
  if (!remoteUrl(dir)) p.push('no "origin" remote');
  return p;
}

function prBody(ctx, f, repoNames, ev) {
  const parent = f.parent ? ctx.backlog.features.find((x) => x.id === f.parent) : null;
  const rows = repoNames.map((n) => {
    const e = latestEvidence(ev, n, ['test', 'manual']);
    return `| ${n} | ${e ? e.result : '-'} | ${e ? String(e.sha).slice(0, 8) : '-'} |`;
  });
  return [
    `## ${f.id} ${f.title}`,
    `Kind: ${f.kind}${parent ? ` (slice of ${parent.id} ${parent.title})` : ''}`,
    `Spec: ${mdPath(f, 'spec.md')}`,
    `Plan: ${mdPath(f, 'plan.md')}`,
    `Handoff: ${handoffRel(ctx, f)}`,
    '',
    '### Verification',
    '| repo | result | sha |', '|---|---|---|', ...rows,
    '',
    `Rework rounds: ${f.rework.length}`,
    '',
    'Generated by specflow deliver',
  ].join('\n') + '\n';
}

/** Plan for one repo: what push and PR action would happen. Reads only. */
function planRepo(ctx, f, name) {
  const repo = ctx.config.repos.find((r) => r.name === name);
  const dir = repoDir(ctx, repo);
  const branch = f.branches[name];
  const cfg = deliveryCfg(ctx);
  const target = cfg.target_branch || defaultBranch(dir);
  const v = prView(dir, branch);
  const plan = { repo: name, dir, branch, target, pr: v.pr || null, action: 'create', reason: '' };
  if (v.error) return { ...plan, action: 'refuse', reason: `gh: ${v.error}` };
  if (v.pr && v.pr.state === 'OPEN') return { ...plan, action: 'update' };
  if (v.pr) return { ...plan, action: 'refuse', reason: `PR #${v.pr.number} for ${branch} is ${v.pr.state}: a new slice gets a new branch` };
  if (!target) return { ...plan, action: 'refuse', reason: 'no target branch: set delivery.target_branch or the repo\'s origin/HEAD' };
  return plan;
}

export function deliver(ctx, f, { dryRun = false } = {}) {
  const cfg = deliveryCfg(ctx);
  if (cfg.mode === 'commit') throw new UserError('delivery mode is commit: pushing and PRs are done by you');
  const ev = readEvidence(ctx, f);
  const names = inDeployOrder(ctx, f.repos);
  const problems = itemProblems(ctx, f).map((m) => `${f.id}: ${m}`);
  for (const n of names) for (const m of repoProblems(ctx, f, n, ev)) problems.push(`${n}: ${m}`);
  if (problems.length) {
    if (!dryRun) throw new UserError(`Cannot deliver ${f.id}:\n${problems.map((x) => `  - ${x}`).join('\n')}`);
    return { id: f.id, dry_run: true, ok: false, problems, repos: [] };
  }
  const plans = names.map((n) => planRepo(ctx, f, n));
  if (dryRun) {
    return { id: f.id, dry_run: true, ok: plans.every((p) => p.action !== 'refuse'), problems: [], repos: plans.map(({ dir, ...p }) => ({ ...p, push: `git push -u origin ${p.branch}` })) };
  }
  const results = [];
  for (const p of plans) {
    if (p.action === 'refuse') { results.push({ repo: p.repo, status: 'refused', detail: p.reason }); continue; }
    const push = git(p.dir, ['push', '-u', 'origin', p.branch]);
    if (!push.ok) { results.push({ repo: p.repo, status: 'failed', detail: `git push failed: ${tail(push.err || push.out, 4)}` }); continue; }
    const sha = headSha(p.dir);
    let pr = p.pr;
    if (p.action === 'create') {
      const bodyFile = path.join(os.tmpdir(), `specflow-pr-${process.pid}-${p.repo}.md`);
      fs.writeFileSync(bodyFile, prBody(ctx, f, names, ev));
      const c = gh(p.dir, ['pr', 'create', '--base', p.target, '--head', p.branch, '--title', `${f.id} ${f.title}`, '--body-file', bodyFile]);
      fs.rmSync(bodyFile, { force: true });
      if (!c.ok) { results.push({ repo: p.repo, status: 'failed', detail: `gh pr create failed (branch was pushed): ${tail(c.err || c.out, 4)}` }); continue; }
      const url = c.out.split(/\s+/).filter((x) => /^https?:\/\//.test(x)).pop() || c.out.split('\n').pop();
      pr = { url, number: Number((url.match(/\/pull\/(\d+)/) || [])[1]) || null, state: 'OPEN' };
    }
    f.delivery[p.repo] = { branch: p.branch, pushed_sha: sha, pr_url: pr.url, pr_number: pr.number, pr_state: pr.state, at: now() };
    logHistory(f, 'link', `deliver ${p.repo}: ${p.action === 'create' ? 'PR opened' : 'PR updated'} ${pr.url}`);
    appendEvidence(ctx, f, { kind: 'delivery', repo: p.repo, sha, result: 'pass', note: pr.url });
    results.push({ repo: p.repo, status: p.action === 'create' ? 'created' : 'updated', pr_url: pr.url, pr_number: pr.number, pushed_sha: sha });
  }
  return { id: f.id, dry_run: false, ok: results.every((r) => r.status === 'created' || r.status === 'updated'), problems: [], repos: results };
}

/** Refreshes the recorded PR state of every delivered repo from gh; records merge evidence once when all are merged. */
export function refreshDelivery(ctx, f) {
  const out = [];
  for (const name of inDeployOrder(ctx, Object.keys(f.delivery))) {
    const d = f.delivery[name];
    const repo = ctx.config.repos.find((r) => r.name === name);
    if (!repo) { out.push({ repo: name, error: 'repo is not registered' }); continue; }
    const v = prView(repoDir(ctx, repo), d.branch);
    if (v.error || !v.pr) { out.push({ repo: name, ...d, error: v.error || 'no PR found for the branch' }); continue; }
    d.pr_state = v.pr.state; d.pr_url = v.pr.url; d.pr_number = v.pr.number;
    out.push({ repo: name, ...d });
  }
  let merged = false;
  const all = Object.values(f.delivery);
  if (all.length && out.every((x) => !x.error) && all.every((d) => d.pr_state === 'MERGED')) {
    merged = true;
    if (!readEvidence(ctx, f).some((e) => e.kind === 'merge' && e.result === 'pass')) {
      appendEvidence(ctx, f, { kind: 'merge', repo: 'all', result: 'pass', note: all.map((d) => d.pr_url).join(' ') });
      logHistory(f, 'link', 'all pull requests merged');
    }
  }
  return { rows: out, merged };
}

export function mergeAll(ctx, f) {
  const cfg = deliveryCfg(ctx);
  if (cfg.mode !== 'push-pr-merge') throw new UserError(`delivery mode is ${cfg.mode}: merging is done by you (only push-pr-merge lets specflow merge)`);
  if (!f.gates.acceptance) throw new UserError(`the acceptance gate of ${f.id} is not approved yet`);
  if (!Object.keys(f.delivery).length) throw new UserError(`${f.id} has no delivered PRs: run \`specflow deliver ${f.id}\` first`);
  refreshDelivery(ctx, f);
  const results = [];
  for (const name of inDeployOrder(ctx, Object.keys(f.delivery))) {
    const d = f.delivery[name];
    if (d.pr_state !== 'OPEN') { results.push({ repo: name, status: 'skipped', detail: `PR is ${d.pr_state}` }); continue; }
    const r = gh(repoDir(ctx, ctx.config.repos.find((x) => x.name === name)), ['pr', 'merge', String(d.pr_number), '--merge']);
    results.push(r.ok ? { repo: name, status: 'merged', pr_url: d.pr_url } : { repo: name, status: 'failed', detail: `gh pr merge failed: ${tail(r.err || r.out, 4)}` });
    if (r.ok) logHistory(f, 'link', `deliver merge ${name}: ${d.pr_url}`);
  }
  const fresh = refreshDelivery(ctx, f);
  return { results, rows: fresh.rows, merged: fresh.merged };
}
